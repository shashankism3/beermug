// Reusable function to render cards onto screen
function displayTrains(trainsList) {
    const gridContainer = document.getElementById("trains-grid");
    if (!gridContainer) return;
    
    gridContainer.innerHTML = "";

    if (trainsList.length === 0) {
        gridContainer.innerHTML = `<p style="grid-column: 1/-1; text-align: center; font-size: 1.2rem; color: #666; padding: 40px 0;">No matching trains found. Try searching another station or train number.</p>`;
        return;
    }

    trainsList.forEach(train => {
        const badgeColor = train.category === "Vande Bharat Sleeper"
            ? "#0f766e"
            : (train.category === "Vande Bharat Express" ? "#1d4ed8" : "#d97706");
        const cardHTML = `
            <a href="${train.link}">
                <div class="card">
                    <span style="display:inline-block;font-size:0.72rem;font-weight:700;color:#fff;background:${badgeColor};padding:2px 8px;border-radius:12px;margin-bottom:6px;">${train.category}</span>
                    <h3>${train.number}</h3>
                    <h4>${train.name}</h4>  
                    <p>Inauguration: ${train.inauguration}</p>    
                </div>
            </a>
        `;
        gridContainer.insertAdjacentHTML('beforeend', cardHTML);
    });
}

